"""Draw the four pictures of the sample episode, "The Lighthouse Keeper".

    uv run python -m scripts.sample_pictures

Every picture is made by this script, from code and a fixed random seed. Nothing is
traced, sampled or generated by an outside model, which is what makes the pictures
original (design doc section 13, rule 2). The results are committed under
samples/lighthouse_keeper/assets, so the demo never needs to run this. Run it again only
to change a picture, then look at the result before committing.
"""

from __future__ import annotations

import math
import sys
from collections.abc import Callable, Sequence
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ASSETS = Path(__file__).resolve().parents[1] / "samples" / "lighthouse_keeper" / "assets"
# The picture area of a scroll is a little wider than it is tall.
WIDTH, HEIGHT = 1360, 1200
# Everything is drawn at twice the size and scaled down, which smooths the edges.
SCALE = 2
SEED = 20261112

Color = tuple[int, int, int]
Point = tuple[float, float]

NIGHT: Color = (10, 16, 38)
INK: Color = (14, 16, 30)
WARM: Color = (255, 200, 87)
CREAM: Color = (236, 226, 200)


def _rng(offset: int) -> np.random.Generator:
    return np.random.default_rng(SEED + offset)


def _canvas(stops: Sequence[tuple[float, Color]]) -> Image.Image:
    """A canvas at drawing size, filled with a vertical gradient through colour stops."""
    width, height = WIDTH * SCALE, HEIGHT * SCALE
    positions = np.array([stop[0] for stop in stops])
    y = np.linspace(0.0, 1.0, height)
    channels = [np.interp(y, positions, [stop[1][c] for stop in stops]) for c in range(3)]
    column = np.stack(channels, axis=1).astype(np.uint8)
    return Image.fromarray(np.repeat(column[:, None, :], width, axis=1), "RGB").convert("RGBA")


def _at(x: float, y: float) -> Point:
    """A point given as fractions of the picture, in drawing pixels."""
    return (x * WIDTH * SCALE, y * HEIGHT * SCALE)


def _finish(image: Image.Image) -> Image.Image:
    return image.convert("RGB").resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS)


def _glow(image: Image.Image, centre: Point, radius: float, color: Color, strength: int) -> None:
    """A soft light: a blurred disc of colour added on top."""
    layer = Image.new("RGBA", image.size, (0, 0, 0, 0))
    r = radius * WIDTH * SCALE
    ImageDraw.Draw(layer).ellipse(
        (centre[0] - r, centre[1] - r, centre[0] + r, centre[1] + r), fill=(*color, strength)
    )
    image.alpha_composite(layer.filter(ImageFilter.GaussianBlur(r * 0.55)))


def _stars(image: Image.Image, rng: np.random.Generator, count: int, lowest: float) -> None:
    draw = ImageDraw.Draw(image)
    for _ in range(count):
        x, y = _at(float(rng.uniform(0, 1)), float(rng.uniform(0, lowest)))
        size = float(rng.uniform(1.2, 3.6)) * SCALE / 2
        shade = int(rng.integers(150, 256))
        draw.ellipse((x - size, y - size, x + size, y + size), fill=(shade, shade, 235, 255))


def _ridge(
    rng: np.random.Generator, level: float, height: float, bumps: float, tilt: float = 0.0
) -> list[Point]:
    """The outline of a row of hills or waves, closed along the bottom of the picture."""
    phases = rng.uniform(0, 2 * math.pi, 3)
    points: list[Point] = []
    for step in range(121):
        x = step / 120
        wave = (
            math.sin(x * bumps * 2 * math.pi + phases[0])
            + 0.5 * math.sin(x * bumps * 4.7 * math.pi + phases[1])
            + 0.25 * math.sin(x * bumps * 9.1 * math.pi + phases[2])
        )
        points.append(_at(x, level - height * wave / 1.75 - tilt * x))
    return [*points, _at(1, 1.05), _at(0, 1.05)]


def _lighthouse(draw: ImageDraw.ImageDraw, foot: Point, height: float, *, lit: bool) -> Point:
    """A lighthouse standing on `foot`. Returns where its lamp is."""
    x, y = foot
    h = height * HEIGHT * SCALE
    wide, narrow = h * 0.13, h * 0.085
    draw.polygon(
        [(x - wide, y), (x + wide, y), (x + narrow, y - h * 0.74), (x - narrow, y - h * 0.74)],
        fill=(*CREAM, 255),
    )
    for band in (0.16, 0.44):
        left = wide - (wide - narrow) * band / 0.74
        draw.polygon(
            [
                (x - left, y - h * band),
                (x + left, y - h * band),
                (x + left * 0.93, y - h * (band + 0.12)),
                (x - left * 0.93, y - h * (band + 0.12)),
            ],
            fill=(178, 52, 44, 255),
        )
    draw.rectangle(
        (x - narrow * 1.5, y - h * 0.78, x + narrow * 1.5, y - h * 0.74), fill=(*INK, 255)
    )
    lamp = (*WARM, 255) if lit else (120, 124, 150, 255)
    draw.rectangle((x - narrow, y - h * 0.9, x + narrow, y - h * 0.78), fill=lamp)
    draw.polygon(
        [(x - narrow * 1.4, y - h * 0.9), (x + narrow * 1.4, y - h * 0.9), (x, y - h)],
        fill=(*INK, 255),
    )
    return (x, y - h * 0.84)


def _ship(image: Image.Image, at: Point, size: float, lean: float) -> None:
    """A small sailing ship as a dark shape, leaning by `lean` degrees."""
    s = int(size * WIDTH * SCALE)
    layer = Image.new("RGBA", (s * 2, s * 2), (0, 0, 0, 0))
    draw = ImageDraw.Draw(layer)
    hull = [(s * 0.45, s * 1.2), (s * 1.55, s * 1.2), (s * 1.38, s * 1.42), (s * 0.62, s * 1.42)]
    draw.polygon(hull, fill=(*INK, 255))
    for mast, top in ((0.82, 0.5), (1.14, 0.38)):
        draw.line((s * mast, s * 1.2, s * mast, s * top), fill=(*INK, 255), width=max(2, s // 40))
        draw.polygon(
            [(s * mast, s * (top + 0.06)), (s * (mast + 0.3), s * 1.08), (s * mast, s * 1.1)],
            fill=(206, 198, 180, 255),
        )
    draw.ellipse((s * 0.96, s * 1.26, s * 1.04, s * 1.34), fill=(*WARM, 255))
    turned = layer.rotate(lean, resample=Image.Resampling.BICUBIC)
    image.alpha_composite(turned, (int(at[0] - s), int(at[1] - s * 1.3)))


# --- the four pictures -------------------------------------------------------------------


def hill_dawn() -> Image.Image:
    """The keeper climbing to the lighthouse before sunrise."""
    rng = _rng(1)
    image = _canvas(
        [(0.0, (16, 22, 56)), (0.35, (52, 48, 104)), (0.62, (214, 122, 96)), (1.0, (255, 196, 120))]
    )
    _stars(image, rng, 70, 0.3)
    _glow(image, _at(0.3, 0.7), 0.24, (255, 214, 150), 190)
    draw = ImageDraw.Draw(image)
    draw.polygon(_ridge(rng, 0.7, 0.05, 1.6), fill=(96, 74, 118, 255))
    draw.polygon(_ridge(rng, 0.78, 0.06, 1.1), fill=(58, 52, 96, 255))
    # The hill rises to the right, where the lighthouse stands.
    hill = [_at(0, 0.98), _at(0.18, 0.9), _at(0.45, 0.72), _at(0.7, 0.5), _at(0.82, 0.44)]
    hill += [_at(0.93, 0.47), _at(1, 0.55), _at(1, 1.05), _at(0, 1.05)]
    draw.polygon(hill, fill=(22, 26, 52, 255))
    path = [_at(0.1, 1.0), _at(0.3, 0.9), _at(0.38, 0.8), _at(0.56, 0.7), _at(0.62, 0.6)]
    path += [_at(0.76, 0.52), _at(0.8, 0.46)]
    draw.line(path, fill=(120, 102, 128, 255), width=10 * SCALE, joint="curve")
    _lighthouse(draw, _at(0.82, 0.445), 0.26, lit=False)
    # The keeper, half way up, dark against the dawn, with a lantern.
    x, y = _at(0.56, 0.626)
    unit = 0.014 * WIDTH * SCALE
    draw.ellipse((x - unit, y - unit * 5, x + unit, y - unit * 3), fill=(*INK, 255))
    draw.polygon(
        [(x - unit * 1.3, y), (x + unit * 1.3, y), (x + unit * 0.9, y - unit * 3.2),
         (x - unit * 0.9, y - unit * 3.2)],
        fill=(*INK, 255),
    )  # fmt: skip
    _glow(image, (x + unit * 2.4, y - unit * 1.6), 0.03, WARM, 230)
    ImageDraw.Draw(image).ellipse(
        (x + unit * 1.9, y - unit * 2.1, x + unit * 2.9, y - unit * 1.1), fill=(*WARM, 255)
    )
    return _finish(image)


def lamp_room() -> Image.Image:
    """The lamp, the glass and the logbook."""
    rng = _rng(2)
    image = _canvas([(0.0, (30, 24, 44)), (0.7, (44, 32, 48)), (1.0, (24, 18, 30))])
    draw = ImageDraw.Draw(image)
    # A round window onto the night.
    left, top = _at(0.62, 0.1)
    right, bottom = _at(0.92, 0.44)
    draw.ellipse((left, top, right, bottom), fill=(*NIGHT, 255), outline=(92, 66, 48, 255),
                 width=14 * SCALE)  # fmt: skip
    for _ in range(18):
        x = float(rng.uniform(left + 60, right - 60))
        y = float(rng.uniform(top + 60, bottom - 60))
        draw.ellipse((x - 3, y - 3, x + 3, y + 3), fill=(220, 224, 240, 255))
    # The lamp: a brass foot, a glass, a flame.
    _glow(image, _at(0.36, 0.42), 0.3, (255, 190, 100), 150)
    draw = ImageDraw.Draw(image)
    draw.polygon([_at(0.27, 0.7), _at(0.45, 0.7), _at(0.41, 0.58), _at(0.31, 0.58)],
                 fill=(150, 104, 52, 255))  # fmt: skip
    draw.rectangle((*_at(0.3, 0.55), *_at(0.42, 0.585)), fill=(190, 138, 66, 255))
    draw.ellipse((*_at(0.27, 0.24), *_at(0.45, 0.57)), fill=(255, 226, 150, 235),
                 outline=(236, 226, 200, 255), width=6 * SCALE)  # fmt: skip
    draw.polygon([_at(0.36, 0.3), _at(0.39, 0.44), _at(0.36, 0.5), _at(0.33, 0.44)],
                 fill=(255, 250, 220, 255))  # fmt: skip
    draw.polygon([_at(0.31, 0.25), _at(0.41, 0.25), _at(0.36, 0.17)], fill=(150, 104, 52, 255))
    # The table and the open logbook, with one line still wet.
    draw.rectangle((*_at(0, 0.7), *_at(1, 1)), fill=(58, 38, 34, 255))
    draw.rectangle((*_at(0, 0.7), *_at(1, 0.725)), fill=(92, 62, 48, 255))
    draw.polygon([_at(0.5, 0.8), _at(0.72, 0.775), _at(0.75, 0.93), _at(0.52, 0.96)],
                 fill=(*CREAM, 255))  # fmt: skip
    draw.polygon([_at(0.72, 0.775), _at(0.93, 0.79), _at(0.95, 0.94), _at(0.75, 0.93)],
                 fill=(222, 210, 182, 255))  # fmt: skip
    for row in range(5):
        y = 0.82 + row * 0.024
        draw.line([_at(0.535, y + 0.004), _at(0.7, y - 0.012)], fill=(120, 104, 96, 255),
                  width=3 * SCALE)  # fmt: skip
    draw.line([_at(0.775, 0.83), _at(0.9, 0.838)], fill=(*INK, 255), width=5 * SCALE)
    return _finish(image)


def storm_sea() -> Image.Image:
    """The night the storm took the stars."""
    rng = _rng(3)
    image = _canvas([(0.0, (12, 14, 24)), (0.5, (34, 40, 56)), (1.0, (20, 30, 44))])
    clouds = Image.new("RGBA", image.size, (0, 0, 0, 0))
    cloud_draw = ImageDraw.Draw(clouds)
    for _ in range(26):
        x, y = _at(float(rng.uniform(-0.1, 1.1)), float(rng.uniform(0.0, 0.42)))
        w, h = float(rng.uniform(260, 620)) * SCALE, float(rng.uniform(70, 150)) * SCALE
        shade = int(rng.integers(20, 62))
        cloud_draw.ellipse((x - w / 2, y - h / 2, x + w / 2, y + h / 2),
                           fill=(shade, shade + 4, shade + 14, 210))  # fmt: skip
    image.alpha_composite(clouds.filter(ImageFilter.GaussianBlur(26 * SCALE)))
    draw = ImageDraw.Draw(image)
    draw.polygon(_ridge(rng, 0.6, 0.05, 2.4), fill=(30, 48, 62, 255))
    _ship(image, _at(0.6, 0.66), 0.16, lean=13)
    draw = ImageDraw.Draw(image)
    for level, height, water in ((0.7, 0.06, (22, 38, 52)), (0.8, 0.07, (14, 26, 40)),
                                 (0.92, 0.08, (8, 14, 26))):  # fmt: skip
        wave = _ridge(rng, level, height, 2.0)
        draw.polygon(wave, fill=(*water, 255))
        draw.line(wave[:121], fill=(150, 170, 180, 120), width=3 * SCALE)
    rain = Image.new("RGBA", image.size, (0, 0, 0, 0))
    rain_draw = ImageDraw.Draw(rain)
    for _ in range(420):
        x, y = _at(float(rng.uniform(-0.1, 1.1)), float(rng.uniform(-0.1, 1.0)))
        length = float(rng.uniform(30, 80)) * SCALE
        rain_draw.line((x, y, x - length * 0.35, y + length), fill=(190, 200, 215, 70),
                       width=SCALE)  # fmt: skip
    image.alpha_composite(rain)
    return _finish(image)


def lighthouse_beam() -> Image.Image:
    """The lamp was burning, and the ship came home."""
    rng = _rng(4)
    image = _canvas([(0.0, (6, 10, 30)), (0.55, (20, 30, 70)), (1.0, (14, 22, 50))])
    _stars(image, rng, 110, 0.5)
    draw = ImageDraw.Draw(image)
    draw.polygon(_ridge(rng, 0.66, 0.012, 3.0), fill=(16, 28, 60, 255))
    cliff = [_at(0, 0.5), _at(0.16, 0.46), _at(0.3, 0.47), _at(0.36, 0.56), _at(0.33, 0.7)]
    cliff += [_at(0.4, 1.05), _at(0, 1.05)]
    draw.polygon(cliff, fill=(*INK, 255))
    lamp = _lighthouse(draw, _at(0.2, 0.465), 0.3, lit=True)
    # The beam reaches across the water to the ship.
    beam = Image.new("RGBA", image.size, (0, 0, 0, 0))
    ImageDraw.Draw(beam).polygon([lamp, _at(1.05, 0.4), _at(1.05, 1.0)], fill=(255, 236, 170, 84))
    image.alpha_composite(beam.filter(ImageFilter.GaussianBlur(14 * SCALE)))
    _glow(image, lamp, 0.07, (255, 236, 170), 255)
    draw = ImageDraw.Draw(image)
    for level, shade in ((0.72, (12, 22, 52)), (0.82, (9, 16, 40)), (0.93, (6, 10, 28))):
        draw.polygon(_ridge(rng, level, 0.014, 3.2), fill=(*shade, 255))
    _ship(image, _at(0.72, 0.7), 0.15, lean=-2)
    glints = ImageDraw.Draw(image)
    for row in range(9):
        x, y = _at(0.72 + float(rng.uniform(-0.012, 0.012)), 0.76 + row * 0.024)
        half = (70 - row * 6) * SCALE
        glints.line((x - half, y, x + half, y), fill=(*WARM, 150), width=4 * SCALE)
    return _finish(image)


PICTURES: dict[str, Callable[[], Image.Image]] = {
    "a_hill_dawn.png": hill_dawn,
    "a_lamp_room.png": lamp_room,
    "a_storm_sea.png": storm_sea,
    "a_lighthouse_beam.png": lighthouse_beam,
}


def build(folder: Path = ASSETS) -> list[Path]:
    """Write every picture. Returns the files written."""
    folder.mkdir(parents=True, exist_ok=True)
    written = []
    for name, draw_picture in PICTURES.items():
        path = folder / name
        draw_picture().save(path, optimize=True)
        written.append(path)
    return written


if __name__ == "__main__":
    for written_path in build():
        sys.stdout.write(f"wrote {written_path.relative_to(ASSETS.parents[2]).as_posix()}\n")
